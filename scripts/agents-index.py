"""Regenerate the "Rule files" index at the end of a project's AGENTS.md.

Usage: python3 scripts/agents-index.py <project-dir> <rules-root>

<rules-root> is the directory holding the converted rules (".claude" or
".agents"). Everything above the "## Rule files" heading is project-owned and
kept as is; the section itself is rebuilt from the installed rule files.
"""

from pathlib import Path
import re
import sys

FOLDERS = ('core', 'languages', 'platforms', 'modules')
HEADING = '## Rule files'


def summarize(front_matter: str) -> str:
    match = re.search(r'^description: (.+)$', front_matter, re.M)
    if not match:
        return ''
    return re.split(r'(?<=[a-z0-9])\. | - ', match.group(1))[0].rstrip('.')


def collect(project: Path, root: str) -> dict[str, list[str]]:
    groups: dict[str, list[str]] = {'always': [], 'paths': [], 'ondemand': []}
    for kind_dir in ('rules', 'rules-on-demand'):
        for folder in FOLDERS:
            for path in sorted((project / root / kind_dir / folder).glob('*.md')):
                front_matter = path.read_text(encoding='utf-8').split('---\n', 2)[1]
                summary = summarize(front_matter)
                relative = path.relative_to(project).as_posix()
                patterns = re.findall(r'^  - "([^"]+)"$', front_matter, re.M)
                if kind_dir == 'rules-on-demand':
                    groups['ondemand'].append(f'- `{relative}`: {summary}')
                elif patterns:
                    scope = ', '.join(f'`{p}`' for p in patterns)
                    groups['paths'].append(f'- `{relative}` ({scope}): {summary}')
                else:
                    groups['always'].append(f'- `{relative}`: {summary}')
    return groups


def render(groups: dict[str, list[str]]) -> str:
    parts = [
        HEADING,
        'Generated by the ruleset installer from the installed rules. '
        'Edit the text above this section only.',
        '### Always apply\n\nRead all of these before any task.\n\n'
        + '\n'.join(groups['always']),
        '### File-scoped\n\nRead before touching matching files, when '
        '`PROJECT.md` section 9 marks the rule active.\n\n' + '\n'.join(groups['paths']),
        '### On demand\n\nRead when `PROJECT.md` marks the module active or the '
        'task touches the topic.\n\n' + '\n'.join(groups['ondemand']),
    ]
    return '\n\n'.join(parts) + '\n'


def main() -> None:
    project, root = Path(sys.argv[1]), sys.argv[2]
    agents = project / 'AGENTS.md'
    owned = agents.read_text(encoding='utf-8').split(HEADING, 1)[0].rstrip('\n')
    agents.write_text(owned + '\n\n' + render(collect(project, root)), encoding='utf-8')


if __name__ == '__main__':
    main()
